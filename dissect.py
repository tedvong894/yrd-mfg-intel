DEFAULT_TYPE = "倒闭关停"


def infer_type(text):
    """根据文本推断问题类型（采集层未标注时兜底）。"""
    t = (text or "").lower()
    best, score = DEFAULT_TYPE, 0
    for tname, kws in TYPE_KEYWORDS.items():
        s = sum(1 for k in kws if k in t)
        if s > score:
            best, score = tname, s
    return best


def get_angles(ptype):
    return PROBLEM_TYPES.get(ptype, PROBLEM_TYPES[DEFAULT_TYPE])["angles"]


def get_template(ptype):
    return PROBLEM_TYPES.get(ptype, PROBLEM_TYPES[DEFAULT_TYPE])


def build_script(item, ptype, region=""):
    """根据问题类型 + 具体问题，产出可拍的短视频脚本框架。"""
    tpl = get_template(ptype)
    angles = get_angles(ptype)
    region = region or item.get("region", "")
    problems = item.get("problems", [])
    # 脚本要点：取前 3 个标准视角 + 具体问题点
    points = [f"① {a['视角']}：{a['要点']}" for a in angles[:3]]
    if problems:
        points.append("④ 本案实锤：" + "；".join(problems[:3]))
    hook = tpl["hook"].format(region=region) if "{region}" in tpl["hook"] else tpl["hook"]
    return {
        "hook": hook,
        "points": points,
        "ending": tpl["ending"],
        "duration": "60-90 秒",
        "style": "真实案例 + 干货口播，前3秒抛冲突，结尾给避坑",
    }
